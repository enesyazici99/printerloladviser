export type StringKey = keyof (typeof STRINGS)["tr"];

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: StringKey, vars?: Record<string, string | number>) => string;
  roleName: (r: Role) => string;
  /** localized static game data (null while loading) */
  data: StaticData | null;
  error: boolean;
}

const Ctx = createContext<I18n | null>(null);

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  // Turkish is rendered first (it is what the static HTML contains); a stored or
  // browser preference is applied right after hydration.
  const [lang, setLangState] = useState<Lang>("tr");
  useEffect(() => {
    let stored: string | null = null;
    try {
      stored = localStorage.getItem("lang");
    } catch {}
    if (stored === "tr" || stored === "en") setLangState(stored);
    else if (!navigator.language.toLowerCase().startsWith("tr")) setLangState("en");
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("lang", l);
    } catch {}
  }, []);
  const { data, error } = useStatic(lang);
  const value = useMemo<I18n>(
    () => ({
      lang,
      setLang,
      t: (key, vars) => translate(lang, key, vars),
      roleName: (r) => translate(lang, `role.${r}` as StringKey),
      data: data ?? null,
      error: Boolean(error),
    }),
    [lang, setLang, data, error]
  );
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n must be used inside I18nProvider");
  return v;
}
